def ler_json(rel):
    """Lê um JSON do pacote."""
    return json.loads((RAIZ / rel).read_text(encoding="utf-8"))


def linha_md(rel, prefixo):
    """Devolve as células da linha de tabela Markdown que começa com ``prefixo``."""
    for linha in (RAIZ / rel).read_text(encoding="utf-8").splitlines():
        if linha.startswith(prefixo):
            return [c.strip() for c in linha.strip().strip("|").split("|")]
    raise KeyError(f"{rel}: linha {prefixo!r} não encontrada")


def num_pt(texto):
    """Converte número impresso em pt-BR ("1.553", "6,8", "21%") para float."""
    t = texto.strip().rstrip("%").replace(".", "").replace(",", ".").replace("−", "-")
    return float(t)


def casas(texto):
    """Casas decimais com que o artigo imprime o número."""
    t = texto.strip().rstrip("%")
    return len(t.split(",")[1]) if "," in t else 0


def wilson(k, n, z=1.959963984540054):
    """Intervalo de Wilson de 95% para k/n."""
    p = k / n
    c = (p + z * z / (2 * n)) / (1 + z * z / n)
    m = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return c - m, c + m


def fisher_bilateral(a, n1, b, n2):
    """Teste exato de Fisher bilateral (soma das tabelas com probabilidade <= a observada)."""
    total_sim, total = a + b, n1 + n2

    def prob(x):
        """Probabilidade hipergeométrica da tabela com x sucessos no grupo 1."""
        return math.comb(n1, x) * math.comb(n2, total_sim - x) / math.comb(total, total_sim)

    p_obs = prob(a)
    lo, hi = max(0, total_sim - n2), min(n1, total_sim)
    return sum(prob(x) for x in range(lo, hi + 1) if prob(x) <= p_obs * (1 + 1e-7))


def n_duas_prop(p1, p2, alpha=0.05, power=0.8):
    """N por grupo para duas proporções (mesma fórmula de analysis/survey-cost/cenarios_custo.py)."""
    z = NormalDist().inv_cdf
    za, zb = z(1 - alpha / 2), z(power)
    pb = (p1 + p2) / 2
    num = za * math.sqrt(2 * pb * (1 - pb)) + zb * math.sqrt(p1 * (1 - p1) + p2 * (1 - p2))
    return (num / (p1 - p2)) ** 2


LINHAS = []


def registra(ident, linha_pt, impresso, formula, entradas, calculado, escala=1.0, corrigido=None):
    """Guarda uma conta: ``calculado * escala`` arredondado como o impresso deve igualá-lo.

    ``corrigido``: valor certo de um impresso errado, documentado em docs/corrections.md; a conta
    fica "corrigido" só se arredondar para ele (e não para o impresso).
    """
    alvo = round(calculado * escala, casas(impresso))
    bate = math.isclose(alvo, num_pt(impresso), abs_tol=1e-9)
    if corrigido and not bate:
        certo = round(calculado * escala, casas(corrigido))
        bate = "corrigido" if math.isclose(certo, num_pt(corrigido), abs_tol=1e-9) else False
    LINHAS.append(
        {
            "id": ident,
            "linha_pt": linha_pt,
            "impresso": impresso,
            "formula": formula,
            "entradas": entradas,
            "calculado": repr(round(calculado * escala, 6)),
            "bate": bate if bate == "corrigido" else ("sim" if bate else "NAO"),
        }
    )


